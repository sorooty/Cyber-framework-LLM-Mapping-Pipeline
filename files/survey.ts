type Key = number | string
type SubGroups<T = number> = { [key: Key]: T }
type FlexibleGroups<T = number> = { [key: Key]: SubGroups<T> | T }
type Groups<T = number> = { [key: Key]: SubGroups<T> }
type SurveyConfig = {
  groups: FlexibleGroups // { [group ID]: { [Sub group ID]: [n questions for this group] }}
  overwriteGroupsId?: { [key: Key]: number } // { [group ID]: new group ID } used to be for group renaming with prefix
  groupsColor?: { [key: Key]: SubGroups<`#${string}` | 'hide'> | `#${string}` | 'hide' }
  flatGroups?: string[] // `${number}.${number}`[]
  complianceOptions?: OaDefsSurveyCompliance[]
  complianceAltText?: Partial<Record<OaDefsSurveyCompliance, string>>
  complianceNA?: Partial<Record<OaDefsSurveyCompliance, ['!' | NAStr, ...NAStr[]]>>
  showRequirementNo?: boolean
  romanNo?: false
}
export type NAStr = `${number}.${number}` | `${number}.${number}-${number}` | `${number}.*`
function defineSurveyConfig (o: Record<OaSurveyType, SurveyConfig>) {
  const out = {} as Record<OaSurveyType, SurveyConfig & { groups: Groups }>
  for (const sType of Object.keys(o) as OaSurveyType[]) {
    const el = o[sType]
    // transform groups to have subgroup:
    const groups = Object.keys(el.groups).reduce((o, grpKey) => {
      const grp = el.groups[grpKey]
      if (typeof grp === 'number') o[grpKey] = { _: grp }
      else o[grpKey] = grp
      return o
    }, {} as Groups)
    out[sType] = { ...el, groups }
    if (!el.complianceNA) continue
    // transform complianceNA (utilities like * or 1-3 or !):
    for (const k2 of Object.keys(el.complianceNA) as OaDefsSurveyCompliance[]) {
      const arr = el.complianceNA[k2]
      if (!arr) continue
      let newArr: NAStr[] = []
      for (let i = 0; i < arr.length; i++) {
        const str = arr[i] as NAStr
        let [grpKey, subGrpKey, selector] = str.split('.')
        if (!selector) [grpKey, subGrpKey, selector] = [grpKey + '', '_', subGrpKey]
        if (selector === '*') { // select all of this group
          newArr = newArr.concat(genGrpItemKeys(grpKey, subGrpKey, groups[grpKey][subGrpKey]))
        } else if (selector.includes('-')) { // select range in this group
          const [start, end] = selector.split('-')
          newArr = newArr.concat(genGrpItemKeys(grpKey, subGrpKey, groups[grpKey][subGrpKey]).slice(+start - 1, +end))
        } else {
          newArr.push(str)
        }
      }
      if (arr[0] === '!') { // inverse array (default remove)
        const all = Object.keys(groups).flatMap(grpKey =>
          Object.keys(groups[grpKey]).flatMap(subGrpKey =>
            genGrpItemKeys(grpKey, subGrpKey, groups[grpKey][subGrpKey])))
        newArr = all.filter(k => newArr.includes(k))
      }
      el.complianceNA[k2] = newArr as [NAStr, ...NAStr[]]
    }
  }
  return out
}
function genGrpItemKeys (grpKey: Key, subGrpKey: Key, n: number) {
  return subGrpKey === '_' // hide subGrpKey for convenience
    ? Array.from({ length: n }).map((_, i) => `${grpKey}.${i + 1}` as NAStr)
    : Array.from({ length: n }).map((_, i) => `${grpKey}.${subGrpKey}.${i + 1}` as NAStr)
}
